declare(strict_types=1);

namespace OCA\Mcp\Modules\Files\Sharing;

use OCA\Mcp\Mcp\Tools\Validation\ArgumentValidationException;
use OCA\Mcp\Platform\FileAccess\CommonMessages;
use OCA\Mcp\Platform\Logging\ExceptionDetails;
use OCA\Mcp\Modules\Files\Presentation\SharingMessages;
use OCA\Mcp\Mcp\Confirmation\PlanChanged;
use OCA\Mcp\Mcp\Confirmation\PlanState;
use OCA\Mcp\Mcp\Tools\Results\ToolFailure;
use OCP\Files\Folder;
use OCP\Files\Node;
use OCP\Share\IManager as IShareManager;
use OCP\Share\IShare;
use Psr\Log\LoggerInterface;

/**
 * files_share: creates a share of an own file or folder, or changes the one that already exists for the same recipient
 * (plan 0.10, decisions 5, 6 and 10).
 *
 * {@see self::plan()} and {@see self::apply()} run the same {@see self::prepare()}, so the confirmed call checks
 * everything again (invariant 1), and it executes only what the plan showed: the plan carries the {@see PlanState} of
 * its action, share and fields before and after, node, recipient and every argument that changes the effect, and a confirmed call that finds another state writes nothing and
 * answers with the new plan ({@see PlanChanged}). The rest it checks again: grant of the type, own and visible node, the
 * administrator's sharing rules, the permission the user has on the node and the validity. The rules the core would refuse with an untranslated
 * exception are checked first through the public IShareManager getters, so the person reads why in their language;
 * whatever the core still refuses becomes a safe message, and only the exception class is logged.
 *
 * A public link (`with: "link"`) goes through {@see LinkShareChange::prepare()} (decision 7, invariants 2 and 4): one link per
 * file, read only, the administrator's link rules (links allowed, enforced password, maximum validity) checked first,
 * and a password generated by {@see LinkPassword} only on the confirmed call, right before the write. The plan says a
 * password will be generated and never holds one; the result of that one execution returns it, and nothing else does.
 *
 * Nextcloud sends its own notification to whoever receives a new share; this class adds none. Stateless: the user is
 * a parameter of every call.
 */
final class ShareWriter {
	/** The plan creates a share. */
	public const CREATE = 'create';
	/** The plan changes the share the user already has for this recipient. */
	public const UPDATE = 'update';
	/** The share already is what the call asks for: the confirmed call writes nothing. */
	public const NONE = 'none';
	/** Longest note for the recipient, in characters, as the schema declares it. */
	public const NOTE_MAX = 500;
	/**
	 * Builds the share plan and effect facade.
	 *
	 * @param ShareAccess $access Share grants and removal checks.
	 * @param ShareRecipientResolver $recipients Recipient resolution.
	 * @param ShareFormatter $formatter Safe share results.
	 * @param LoggerInterface $logger Safe failure logging.
	 * @param LinkPassword $passwords Confirmed-call password generation.
	 * @param PlanState $states Signed plan state.
	 * @param RecipientShareChange $recipientChanges Person and group preparation.
	 * @param LinkShareChange $linkChanges Public link preparation.
	 * @param ShareCoreWrite $core Public core writes.
	 */
	public function __construct(
		private ShareAccess $access,
		private ShareRecipientResolver $recipients,
		private ShareFormatter $formatter,
		private LoggerInterface $logger,
		private LinkPassword $passwords,
		private PlanState $states,
		private RecipientShareChange $recipientChanges,
		private LinkShareChange $linkChanges,
		private ShareCoreWrite $core,
	) {}

	/**
	 * The plan of files_share: what would be created or changed, before → after, and the warnings. Writes nothing.
	 *
	 * @param Folder $userFolder the user's folder
	 * @param string $uid authenticated user
	 * @param array{path:string, with:string, permission?:string, expires?:string, note?:string} $arguments validated arguments
	 * @return array{action:string, path:string, isDir:bool, with:array{type:string, id:string, displayName:string}, shareId:string|null, before:array{permission:string, reshare:bool, expires:string|null, note:string}|null, after:array{permission:string, reshare:bool, expires:string|null, note:string|null}, expiresSource:string, notifies:bool, timezone:string, warnings:list<array{message:string}>, message:string, plan_state:string, password?:array{before:bool|null, after:string, required:bool}}
	 *   `plan_state` is what the confirmed call gives back ({@see PlanState}). `expiresSource` says where `after.expires`
	 *   comes from: requested, kept, default (the administrator's, applied by the core) or none. `password` exists for a link only and never holds a password: `before` is whether the link
	 *   has one (null for a new link), `after` is new (generated on the confirmed call), kept or none, and `required`
	 *   whether the administrator enforces it
	 * @throws ArgumentValidationException for an unknown recipient, a level outside view/edit or an unusable date
	 * @throws ToolFailure for every other refusal, with a translated reason
	 */
	public function plan(Folder $userFolder, string $uid, array $arguments): array {
		return $this->planOf($this->prepare($userFolder, $uid, $arguments), $uid);
	}

	/**
	 * The plan of one prepared change, with its {@see PlanState}.
	 *
	 * @param array<string, mixed> $change what {@see self::prepare()} returned
	 * @param string $uid authenticated user, part of the state
	 * @param bool $changed whether the confirmed call found this state instead of the approved one: the warning that
	 *   says so comes first
	 * @return array<string, mixed> the plan, in the shape {@see self::plan()} documents
	 */
	private function planOf(array $change, string $uid, bool $changed = false): array {
		$warnings = $change['warnings'];
		if ($changed) {
			array_unshift($warnings, SharingMessages::sharePlanChanged());
		}
		return [
			'action' => $change['action'],
			'path' => $change['path'],
			'isDir' => $change['folder'],
			'with' => $change['recipient']->toArray(),
			'shareId' => $change['existing']?->getFullId(),
			'before' => $change['before'],
			'after' => $change['after'],
			'expiresSource' => $change['expiresSource'],
			'notifies' => $change['action'] === self::CREATE && $change['recipient']->kind !== ShareRecipient::LINK,
			'timezone' => $change['timezone']->getName(),
			'warnings' => array_map(static fn (string $message): array => ['message' => $message], $warnings),
			'message' => $change['action'] === self::NONE ? SharingMessages::planShareNothing() : CommonMessages::planNothingChanged(),
			PlanState::ARGUMENT => $this->stateOf($change, $uid),
		] + ($change['passwordPlan'] === null ? [] : ['password' => $change['passwordPlan']]);
	}

	/**
	 * The fingerprint of what the plan shows and of everything the call asked for: the action, the share and its fields
	 * before (permission bits, validity, note, whether it has a password), the node (id and path), the recipient (kind
	 * and id), what the share becomes, and every argument that changes the effect as the call gave it (permission,
	 * expires, note, whether to generate a password). A confirmed call for another recipient, path or field therefore
	 * never matches the plan of this one. No password is part of it.
	 *
	 * @param array<string, mixed> $change what {@see self::prepare()} returned
	 * @param string $uid authenticated user, so the value never confirms for another account
	 * @return string the opaque {@see PlanState} of the change
	 */
	private function stateOf(array $change, string $uid): string {
		return $this->states->of('files_share', $uid, [
			'action' => $change['action'],
			'shareId' => $change['existing']?->getFullId(),
			'node' => ['id' => $change['node']->getId(), 'path' => $change['path']],
			'recipient' => ['kind' => $change['recipient']->kind, 'id' => $change['recipient']->id],
			'before' => ShareAccess::snapshot($change['existing']),
			'bits' => $change['bits'],
			'after' => $change['after'],
			'password' => $change['passwordPlan'],
			'requested' => $change['requested'],
		]);
	}

	/**
	 * The arguments that change the effect, as the call gave them, for {@see self::stateOf()}: two calls that differ in
	 * any of them are two different approvals even when they would end in the same snapshot.
	 *
	 * @param array<string, mixed> $arguments validated arguments
	 * @return array{permission:string, expires:string|null, note:string|null, password:bool|null}
	 */
	private static function requested(array $arguments): array {
		return [
			'permission' => (string)($arguments['permission'] ?? \OCA\Mcp\Platform\FileAccess\SharePermission::VIEW),
			'expires' => isset($arguments['expires']) ? (string)$arguments['expires'] : null,
			'note' => isset($arguments['note']) ? (string)$arguments['note'] : null,
			'password' => isset($arguments['password']) ? $arguments['password'] === true : null,
		];
	}

	/**
	 * Applies the plan after checking everything again: createShare, updateShare, or nothing when nothing changes. The
	 * call gives back the `plan_state` of the plan it confirms, and nothing is written unless it is still this state.
	 *
	 * @param Folder $userFolder the user's folder
	 * @param string $uid authenticated user
	 * @param array{path:string, with:string, permission?:string, expires?:string, note?:string} $arguments validated arguments
	 * @return array<string, mixed> the share as {@see ShareFormatter::item()} shows it, plus `action` and `changed`; when
	 *   this call generated a link password, also `password` (the only place it is ever returned) and `passwordNotice`
	 * @throws ArgumentValidationException as {@see self::plan()}, and without `plan_state` once nothing else refuses
	 * @throws PlanChanged when the share is not in the state the plan showed; nothing is written
	 * @throws ToolFailure as {@see self::plan()}, when no acceptable password can be generated, and with a translated
	 *   reason when the core refuses; once a password may exist, every unexpected Throwable becomes one of these too, so
	 *   nothing carrying it reaches the registry, which logs the message of what escapes
	 */
	public function apply(Folder $userFolder, string $uid, array $arguments): array {
		$change = $this->prepare($userFolder, $uid, $arguments);
		PlanState::require($arguments);
		if (!PlanState::matches($this->stateOf($change, $uid), $arguments)) {
			throw new PlanChanged($this->planOf($change, $uid, true));
		}
		$share = $change['existing'];
		$password = null;
		if ($change['action'] !== self::NONE) {
			// Generated only now, after every check passed again, so a refused call never produces a password.
			$password = $change['generatePassword'] ? $this->passwords->generate() : null;
			$share = $this->core->write($change, $uid, $password);
		}
		try {
			$item = $this->formatter->item($share, $change['path'], $this->access->isRemovable($share, $uid));
		} catch (\Throwable $e) {
			// A password may exist by now: keep the native failure text out of both the response and the log.
			$this->logger->warning('MCP share result failed: {exception_class} (code {exception_code})', ['app' => 'mcp', 'exception_class' => $e::class, 'exception_code' => ExceptionDetails::code($e)]);
			throw new ToolFailure(SharingMessages::shareRefused());
		}
		$result = ['action' => $change['action'], 'changed' => $change['action'] !== self::NONE] + $item;
		if ($password !== null) {
			$result['password'] = $password;
			$result['passwordNotice'] = SharingMessages::linkPasswordShownOnce();
		}
		return $result;
	}

	/**
	 * Everything the plan shows and the write needs, checked in the order the person would want the reason: who, may
	 * I, which file, what the server allows, what I may give, until when. The node comes before any other refusal
	 * that depends on it, so a hidden node always answers "not found".
	 *
	 * @param Folder $userFolder the user's folder
	 * @param string $uid authenticated user
	 * @param array<string, mixed> $arguments validated arguments
	 * @return array{action:string, node:Node, path:string, folder:bool, recipient:ShareRecipient, existing:IShare|null, bits:int, expires:\DateTime|null, note:string|null, before:array<string, mixed>|null, after:array<string, mixed>, expiresSource:string, timezone:\DateTimeZone, warnings:list<string>, generatePassword:bool, passwordPlan:array{before:bool|null, after:string, required:bool}|null, requested:array{permission:string, expires:string|null, note:string|null, password:bool|null}}
	 * @throws ArgumentValidationException|ToolFailure for any refusal
	 */
	private function prepare(Folder $userFolder, string $uid, array $arguments): array {
		$recipient = $this->recipients->resolve((string)$arguments['with'], 'with');
		$this->access->assertGranted($uid, $recipient->shareType());
		$change = $recipient->kind === ShareRecipient::LINK
			? $this->linkChanges->prepare($userFolder, $uid, $arguments, $recipient)
			: $this->recipientChanges->prepare($userFolder, $uid, $arguments, $recipient);
		$change['requested'] = self::requested($arguments);
		return $change;
	}
}
