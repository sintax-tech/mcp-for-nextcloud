declare(strict_types=1);

/**
 * Reads the gdb output of crash-evidence.sh on stdin and prints one line saying where the faulting instruction of a
 * crashed Apache worker lies: in a mapped file (apache2, libphp.so, opcache.so, an extension, libc...) or in the
 * anonymous shared memory of OPcache, where the JIT buffer lives (`/dev/zero (deleted)` in the mappings of a core).
 * Runs with the container's own PHP, so the 64-bit addresses are compared as integers on every runner.
 */
$output = (string)stream_get_contents(STDIN);
if (preg_match('/^\$\d+ = (0x[0-9a-f]+)$/m', $output, $match) !== 1) {
	echo "faulting instruction: unknown (gdb printed no \$pc)\n";
	return;
}
$pc = hexdec($match[1]);
preg_match_all('/^\s*(0x[0-9a-f]+)\s+(0x[0-9a-f]+)\s+0x[0-9a-f]+\s+0x[0-9a-f]+\s+(?:[rwxps-]{4}\s+)?(.+)$/m', $output, $mappings, PREG_SET_ORDER);
foreach ($mappings as [, $start, $end, $file]) {
	if ($pc >= hexdec($start) && $pc < hexdec($end)) {
		$file = trim($file);
		$where = $file === '/dev/zero (deleted)'
			? 'the anonymous shared memory of OPcache, where the JIT buffer lives (code generated by the JIT)'
			: $file;
		echo "faulting instruction: {$match[1]} in $where\n";
		return;
	}
}
echo "faulting instruction: {$match[1]} outside every mapped file (anonymous memory: generated code or a corrupted jump)\n";
