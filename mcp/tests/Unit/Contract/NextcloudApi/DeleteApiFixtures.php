declare(strict_types=1);
namespace OCA\Mcp\Tests\Unit\Contract\NextcloudApi;

/** Adds only deletion API surfaces parsed from checksum-pinned official sources, without executing those sources. */
final class DeleteApiFixtures {
	/**
	 * @param string $major Server major present in delete-sources.json.
	 * @param string $tree Downloaded source tree for that major.
	 * @param string $directory Fixture directory containing the manifest and the existing server fixture.
	 * @return void
	 */
	public static function generate(string $major, string $tree, string $directory): void {
		$pins = json_decode((string)file_get_contents($directory . '/delete-sources.json'), true, 512, JSON_THROW_ON_ERROR);
		if (!isset($pins[$major])) {
			throw new \InvalidArgumentException('Unknown deletion source major');
		}
		foreach ($pins[$major] as $path => $pin) {
			if (!is_file($tree . '/' . $path) || hash_file('sha256', $tree . '/' . $path) !== $pin['sha256']) {
				throw new \RuntimeException('Official source checksum mismatch: ' . $path);
			}
		}
		$path = $directory . '/' . $major . '.php';
		$fixture = require $path;
		$parser = new SourceParser($tree);
		foreach (['OCA\\Files_Trashbin\\Events\\MoveToTrashEvent', 'OCA\\Files_Trashbin\\Trash\\ITrashManager',
			'OCA\\Files_Trashbin\\Trash\\LegacyTrashBackend', 'OCP\\Encryption\\IManager',
			'OCP\\Exceptions\\AbortedEventException', 'OC\\Files\\Storage\\Local', 'OC\\Lock\\NoopLockingProvider'] as $class) {
			$surface = $parser->surface($class);
			if ($surface === null) {
				throw new \RuntimeException('Official source lacks ' . $class);
			}
			$fixture['classes'][$class] = $surface;
		}
		ksort($fixture['classes']);
		$original = (string)file_get_contents($path);
		$header = substr($original, 0, (int)strpos($original, 'return ['));
		$header = (string)preg_replace('~// Deletion surfaces generated[^\n]*\n~', '', $header);
		$header .= "// Deletion surfaces generated by generate-delete.php; official source URLs/SHAs in delete-sources.json.\n";
		FixtureFile::write($path, $header, $fixture);
		echo 'Generated verified deletion surfaces for NC' . $major . "\n";
	}
}
