declare(strict_types=1);
namespace OCA\Mcp\Tests\Unit\Contract\NextcloudApi;

/** Adds only the Deck LabelService surface parsed from checksum-pinned official sources, without executing them. */
final class LabelApiFixtures {
	/** The class the board label tools resolve by name. */
	public const CLASSES = ['OCA\\Deck\\Service\\LabelService'];

	/**
	 * @param string $major Server major present in label-sources.json.
	 * @param string $tree Downloaded source tree for that major (apps/deck/lib/... at the pinned paths).
	 * @param string $directory Fixture directory containing the manifest and the existing server fixture.
	 * @return void
	 */
	public static function generate(string $major, string $tree, string $directory): void {
		$pins = json_decode((string)file_get_contents($directory . '/label-sources.json'), true, 512, JSON_THROW_ON_ERROR);
		if (!isset($pins[$major])) {
			throw new \InvalidArgumentException('Unknown label source major');
		}
		$path = $directory . '/' . $major . '.php';
		$fixture = require $path;
		if (($fixture['sources']['deck'] ?? null) !== $pins[$major]['deck']) {
			throw new \RuntimeException('Deck release differs from the fixture: ' . $pins[$major]['deck']);
		}
		foreach ($pins[$major]['files'] as $file => $pin) {
			if (!is_file($tree . '/' . $file) || hash_file('sha256', $tree . '/' . $file) !== $pin['sha256']) {
				throw new \RuntimeException('Official source checksum mismatch: ' . $file);
			}
		}
		$parser = new SourceParser($tree);
		foreach (self::CLASSES as $class) {
			$surface = $parser->surface($class);
			if ($surface === null) {
				throw new \RuntimeException('Official source lacks ' . $class);
			}
			$fixture['classes'][$class] = $surface;
		}
		ksort($fixture['classes']);
		$original = (string)file_get_contents($path);
		$header = substr($original, 0, (int)strpos($original, 'return ['));
		$header = (string)preg_replace('~// Label surfaces generated[^\n]*\n~', '', $header);
		$header .= "// Label surfaces generated by generate-labels.php; official source URLs/SHAs in label-sources.json.\n";
		FixtureFile::write($path, $header, $fixture);
		echo 'Generated verified label surfaces for NC' . $major . "\n";
	}
}
