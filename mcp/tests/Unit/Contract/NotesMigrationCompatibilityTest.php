declare(strict_types=1);

namespace OCA\Mcp\Tests\Unit\Contract;

use OCA\Mcp\Tests\Support\Notes\NotesTestCase;
use OCA\Mcp\L10n\Translator;
use OCA\Mcp\Tests\Unit\L10n\JsonL10n;
use OCA\Mcp\Mcp\Guide\ToolGuide;
final class NotesMigrationCompatibilityTest extends NotesTestCase
{

    public static function encode(mixed $value): string
    {
        return json_encode($value, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);
    }

    /** Capture utility used once before migration; tests only compare the committed files. */

    public function capture(): array
    {
        $this->setUp();
        $raw = $this->module->definitions();
        $registry = $this->registry();
        $published = $registry->definitions('alice');
        $definitions = ['raw' => $raw, 'published' => $published, 'guide' => (new ToolGuide([$this->module]))->result($published, ['module' => 'notes'])];
        $plans = [];
        foreach (['en', 'pt_BR'] as $locale) {
            Translator::use(new JsonL10n($locale));
            foreach ($this->writes() + ['new_category' => ['title' => 'Created', 'category' => 'New/Sub'], 'shared_edit' => ['id' => $this->id, 'content' => 'Shared change'], 'locked_edit' => ['id' => $this->id, 'content' => 'Locked change']] as $key => $args) {
                $name = match ($key) {
                    'new_category' => 'notes_create',
                    'shared_edit', 'locked_edit' => 'notes_edit',
                    default => $key,
                };
                $path = '/alice/files/Notes/Work/Before.md';
                $this->tree->nodes[$path]['scope'] = $key === 'shared_edit' ? 'shared' : 'personal';
                $this->locks->locks = [];
                if ($key === 'locked_edit') {
                    $this->locks->put(new \OCA\Mcp\Tests\Support\Platform\FileAccess\Locks\FakeLock($this->id, \OCP\Files\Lock\ILock::TYPE_APP, 'text'));
                }
                $before = $this->tree->nodes;
                $plan = $this->module->preview($name, $args, 'alice');
                self::assertSame($before, $this->tree->nodes);
                self::assertSame([], $this->tree->ops);
                $plans[$locale][$key] = ['arguments' => $args, 'plan' => $plan, 'rendered' => $this->module->renderPlan($name, $plan)];
            }
        }
        Translator::reset();
        $results = [];
        foreach (['notes_list' => [], 'notes_search' => ['query' => 'Original', 'limit' => 20, 'category' => ''], 'notes_read' => ['id' => $this->id]] + $this->writes() as $name => $args) {
            $this->setUp();
            $result = $this->module->call($name, $args, 'alice');
            // File mutation mtimes are generated by the shared host fixture, not the Notes contract.
            $body = json_decode($result['content'][0]['text'], true, 512, JSON_THROW_ON_ERROR);
            $normalize = function (&$data) use (&$normalize): void {
                if (!is_array($data)) {
                    return;
                }
                foreach ($data as $key => &$value) {
                    if ($key === 'modified') {
                        $value = 1700000000;
                    } else {
                        $normalize($value);
                    }
                }
            };
            $normalize($body);
            $result['content'][0]['text'] = json_encode($body, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_THROW_ON_ERROR);
            $results[$name] = $result;
        }
        $this->setUp();
        foreach (['missing' => ['id' => 99999], 'too_large' => ['id' => $this->id, 'content' => str_repeat('x', 1048577)]] as $key => $args) {
            try {
                $this->module->call($key === 'missing' ? 'notes_read' : 'notes_edit', $args, 'alice');
                self::fail('Expected refusal');
            } catch (\OCA\Mcp\Mcp\Tools\Results\ToolFailure $e) {
                $results[$key] = ['type' => $e::class, 'message' => $e->getMessage()];
            }
        }
        $this->setUp();
        $this->tree->failMove[] = '/alice/files/Notes/Work/Before.md';
        try {
            $this->module->call('notes_edit', $this->writes()['notes_edit'], 'alice');
            self::fail('Expected partial edit');
        } catch (\OCA\Mcp\Mcp\Tools\Results\ToolFailure $e) {
            $results['partial_edit'] = ['message' => $e->getMessage(), 'content' => $this->tree->nodes['/alice/files/Notes/Work/Before.md']['content']];
        }
        $this->setUp();
        $tools = $this->registry();
        $policy = \OCA\Mcp\Tests\Unit\InMemoryConfig::policy($this->config->mock($this), new \OCA\Mcp\Tests\Unit\OAuth\InMemoryOAuthStore());
        $guard = $this->createMock(\OCA\Mcp\Access\Visibility\VisibilityGuard::class);
        $resources = new \OCA\Mcp\Mcp\Resources\ResourceRegistry($tools, $policy, $this->apps, $this->users, $this->createMock(\OCA\Mcp\Modules\Files\Contracts\FileResourceReader::class), new \OCA\Mcp\Modules\Notes\Resources\NextcloudNoteResourceReader(new \OCA\Mcp\Modules\Notes\Storage\NotesFolders($this->root, $this->config->mock($this)), new \OCA\Mcp\Modules\Notes\Storage\NoteLookup(), new \OCA\Mcp\Modules\Notes\Content\NoteContent(), $guard), new ToolGuide([$this->module]));
        $results['resource'] = $resources->read('nc://notes/' . $this->id, 'alice');
        return ['definitions' => $definitions, 'plans' => $plans, 'results' => $results];
    }

    public function testFrozenPublicationPlansAndResults(): void
    {
        foreach ($this->capture() as $name => $actual) {
            self::assertSame(file_get_contents(__DIR__ . '/../../Support/Notes/Compatibility/' . $name . '.json'), self::encode($actual), $name);
        }
    }

    public function testNotesDirectWritesAndRegistryApprovalRemainDistinct(): void
    {
        foreach (array_keys($this->writes()) as $name) {
            $this->setUp();
            $args = $this->writes()[$name];
            $registry = $this->registry();
            $before = $this->tree->nodes;
            foreach ([[], ['confirm' => false]] as $confirm) {
                self::assertTrue($registry->call($name, $args + $confirm, 'alice')['structuredContent']['requiresConfirmation']);
                self::assertSame($before, $this->tree->nodes);
                self::assertSame([], $this->tree->ops);
            }
            self::assertArrayNotHasKey('isError', $registry->call($name, $args + ['confirm' => true], 'alice'));
            self::assertNotEmpty($this->tree->ops);
            $this->setUp();
            $this->module->call($name, $this->writes()[$name], 'alice');
            self::assertNotEmpty($this->tree->ops, 'Direct call remains an execution path: ' . $name);
        }
    }

    public function testInitialRootResolutionOrderAndCount(): void
    {
        foreach (['notes_list' => [], 'notes_search' => ['query' => '', 'limit' => 20], 'notes_read' => ['id' => $this->id]] as $name => $args) {
            $this->setUp();
            $this->module->call($name, $args, 'alice');
            self::assertSame(1, $this->rootReads, $name);
        }
        foreach (['notes_edit' => ['id' => $this->id], 'notes_delete' => ['id' => $this->id], 'notes_create' => ['title' => 'New', 'content' => str_repeat('x', 1048577)]] as $name => $args) {
            foreach ([false, true] as $preview) {
                $this->setUp();
                $this->enabledApps = ['notes'];
                $this->rootFailure = new \OCP\Files\NotFoundException();
                try {
                    $preview ? $this->module->preview($name, $args, 'alice') : $this->module->call($name, $args, 'alice');
                    self::fail('Expected refusal');
                } catch (\OCA\Mcp\Mcp\Tools\Results\ToolFailure $e) {
                    $earlySize = $name === 'notes_create' && !$preview;
                    self::assertSame($earlySize ? 'Note exceeds the limit of 1048576 bytes.' : \OCA\Mcp\Platform\FileAccess\FileAccessMessages::notFound(), $e->getMessage());
                    self::assertSame($earlySize ? 0 : 1, $this->rootReads);
                }
            }
        }
    }

    public function testSearchCandidateLimitAndUnicodeBoundaries(): void
    {
        $root = $this->createMock(\OCP\Files\Folder::class);
        $file = $this->createMock(\OCP\Files\File::class);
        $file->method('getName')->willReturn('Match.MD');
        $root->method('getDirectoryListing')->willReturn(array_fill(0, 2001, $file));
        $repo = new \OCA\Mcp\Modules\Notes\Storage\NoteLookup();
        self::assertCount(2000, $repo->all($root));
        $this->tree->nodes['/alice/files/Notes/Work/Before.md']['content'] = "bad\xff café";
        $result = $this->module->call('notes_search', ['query' => 'CAFÉ', 'limit' => 20, 'category' => ''], 'alice');
        $body = json_decode($result['content'][0]['text'], true, 512, JSON_THROW_ON_ERROR);
        self::assertCount(1, $body);
        self::assertSame("bad? café", $body[0]['snippet']);
    }

    public function testInterleavedUsersAndLocalesDoNotLeakThroughSharedModule(): void
    {
        $bob = new \OCA\Mcp\Tests\Support\Platform\FileAccess\FakeTree($this, '/bob/files');
        $bobId = $bob->addFile('/bob/files/Notes/Personal.md', 'Bob only');
        $this->userTrees['bob'] = $bob;
        foreach ([['alice', $this->id, '# Original', 'en'], ['bob', $bobId, 'Bob only', 'pt_BR'], ['alice', $this->id, '# Original', 'es']] as [$user, $id, $text, $locale]) {
            Translator::use(new JsonL10n($locale));
            $body = json_decode($this->module->call('notes_read', ['id' => $id], $user)['content'][0]['text'], true, 512, JSON_THROW_ON_ERROR);
            self::assertSame($text, $body['content']);
            $plan = $this->module->preview('notes_edit', ['id' => $id, 'content' => 'Change'], $user);
            self::assertSame($text, $plan['note']['before']['content']);
            self::assertSame(\OCA\Mcp\Modules\Notes\Presentation\NotesPlanMessages::planEdit(), $plan['message']);
        }
        self::assertSame([], $bob->ops);
        self::assertSame([], $this->tree->ops);
    }

    public function testDisabledAppRejectsPublicationAndCallsBeforeStorageAccess(): void
    {
        $registry = $this->registry();
        $this->enabledApps = [];
        self::assertSame([], $registry->definitions('alice'));
        try {
            $registry->call('notes_read', ['id' => $this->id], 'alice');
            self::fail('Disabled app must reject the call');
        } catch (\OCA\Mcp\Mcp\Tools\Validation\UnknownToolException $e) {
            self::assertSame('Unknown tool', $e->getMessage());
        }
        self::assertSame(0, $this->rootReads);
    }
}
