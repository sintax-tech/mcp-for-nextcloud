/** Synthetic pre-extraction evidence. Captures are compared, never regenerated by tests. */
final class SharedMcpMigrationCompatibilityTest extends TestCase {
    private bool $enabled = true;
    private string $version = '';
    private bool $role = true;
    private array $events = [];
    private ?\Throwable $failure = null;
    private bool $auditFails = false;
    private bool $loggerFails = false;
    private bool $roleFails = false;

    protected function tearDown(): void { Translator::reset(); }

    private function boot(?array $modules = null): array {
        $config = new InMemoryConfig();
        $policy = InMemoryConfig::policy($config->mock($this), new InMemoryOAuthStore());
        $apps = $this->createMock(IAppManager::class);
        $apps->method('isEnabledForUser')->willReturnCallback(fn () => $this->enabled);
        $apps->method('getAppVersion')->willReturnCallback(fn () => $this->version);
        $users = $this->createMock(IUserManager::class);
        $users->method('get')->willReturn($this->createMock(IUser::class));
        $logger = $this->createMock(LoggerInterface::class);
        $logger->method('error')->willReturnCallback(function (): void {
            $this->events[] = 'logger';
            if ($this->loggerFails) { throw new \RuntimeException('synthetic logger failure'); }
        });
        $availability = new \OCA\Mcp\Mcp\Tools\Discovery\ToolAvailability($policy, $apps, $users);
        $registry = new ToolRegistry($modules ?? [$this->module()], $availability, new \OCA\Mcp\Mcp\Tools\Execution\ToolExecutor($availability, $logger));
        $fileReader = $this->createMock(\OCA\Mcp\Modules\Files\Contracts\FileResourceReader::class);
        $fileReader->method('read')->willThrowException(new ToolFailure('Synthetic resource refusal'));
        $resources = new ResourceRegistry($registry, $policy, $apps, $users,
            $fileReader,
            $this->createMock(\OCA\Mcp\Modules\Notes\Contracts\NoteResourceReader::class), $registry->guide());
        return [$registry, $policy, new McpProtocol(new \OCA\Mcp\Mcp\Protocol\ToolRequests($registry),
            new \OCA\Mcp\Mcp\Protocol\PromptRequests(new PromptCatalog(), $policy),
            new \OCA\Mcp\Mcp\Protocol\ResourceRequests($resources), $logger), $resources];
    }

    private function module(): ToolModule {
        $definition = static fn (string $name, string $operation, array $extra = []): array => [
            'name' => $name, 'description' => 'Synthetic shared contract.',
            'inputSchema' => ['type' => 'object', 'properties' => ['n' => ['type' => 'integer', 'default' => 5]], 'additionalProperties' => false],
            'module' => 'files', 'operation' => $operation,
        ] + $extra;
        return new class([
            $definition('files_read', 'read'), $definition('files_edit', 'edit'),
            $definition('notes_list', 'read', ['app' => 'deck']),
            $definition('files_share', 'share', ['grantAnyOf' => ['share', 'link']]),
        ], fn () => $this->allowed(), fn ($n, $a, $u) => $this->execute($n, $a, $u), fn ($o, $a) => $this->audit($o, $a)) implements ToolModule, RestrictedModule {
            public function __construct(private array $definitions, private \Closure $role, private \Closure $call, private \Closure $audit) {}
            public function definitions(): array { return $this->definitions; }
            public function permits(string $userId): bool { return ($this->role)(); }
            public function call(string $name, array $arguments, string $userId): array { return ($this->call)($name, $arguments, $userId); }
            public function audit(string $tool, string $userId, string $outcome, array $arguments): void { ($this->audit)($outcome, $arguments); }
        };
    }

    private function allowed(): bool {
        if ($this->roleFails) { throw new \RuntimeException('synthetic role failure'); }
        return $this->role;
    }
    private function execute(string $name, array $arguments, string $uid): array {
        $this->events[] = ['call', $arguments, $uid];
        if ($this->failure) { throw $this->failure; }
        return ToolResult::structured('Synthetic result', ['arguments' => $arguments]);
    }
    private function audit(string $outcome, array $arguments): void {
        $this->events[] = [$outcome, $arguments];
        if ($this->auditFails) { throw new \RuntimeException('synthetic audit failure'); }
    }
    private function grants(GrantPolicy $policy, string $uid, bool $enabled): void {
        foreach (GrantPolicy::CATALOG as $module => $operations) {
            foreach ($operations as $operation) { $policy->setGrant($uid, $module, $operation, $enabled); }
        }
    }
    private function refused(\Closure $call): void {
        try { $call(); self::fail('Expected refusal'); }
        catch (\InvalidArgumentException $e) { self::assertNotSame('', $e->getMessage()); }
    }

    /** Public only for the one-time external baseline capture command. */
    public function capture(): array {
        $modules = [];
        foreach (Application::MODULES as $class) {
            if ($class === \OCA\Mcp\Modules\Logs\LogsModule::class) {
                $access = $this->createMock(\OCA\Mcp\Access\Logs\LogsAccess::class);
                $access->method('permits')->willReturn(true);
                $modules[] = new $class(['logs_list' => static fn () => throw new \LogicException('No reads during discovery'), 'logs_analyze' => static fn () => throw new \LogicException('No reads during discovery')], static fn () => $access, static fn () => throw new \LogicException('No audit during discovery'));
            } else {
                // Catalog and guide notes are static; no feature operation may run here.
                $modules[] = (new \ReflectionClass($class))->newInstanceWithoutConstructor();
            }
        }
        [$registry, $policy, $protocol, $resources] = $this->boot($modules);
        $publication = [];
        foreach (['en', 'pt_BR', 'es'] as $locale) {
            Translator::use(new JsonL10n($locale));
            foreach (['default', 'none', 'all', 'link'] as $mode) {
                $uid = $mode;
                if ($mode !== 'default') { $this->grants($policy, $uid, $mode === 'all'); }
                if ($mode === 'link') { $policy->setGrant($uid, 'files', 'link', true); }
                $publication[$locale][$mode] = ['published' => $registry->list($uid), 'definitions' => $registry->definitions($uid),
                    'guide' => $registry->call('mcp_guide', [], $uid), 'resource' => $resources->read('mcp://guide', $uid),
                    'templates' => $resources->templates($uid), 'prompts' => (new PromptCatalog())->list($policy, $uid)];
            }
            $publication[$locale]['raw'] = array_map(static fn ($m) => $m->definitions(), $modules);
            $publication[$locale]['protocol'] = $protocol->handle('{"jsonrpc":"2.0","id":1,"method":"tools/list"}', \OCA\Mcp\Mcp\Protocol\ProtocolMetadata::VERSION, 'all');
        }
        Translator::reset();
        $protocolCases = [];
        $requests = ['{bad', '{"jsonrpc":"2.0","method":"notifications/initialized"}', '{"jsonrpc":"2.0","id":null,"method":"ping"}'];
        foreach (['ping', 'tools/list', 'tools/call', 'prompts/list', 'prompts/get', 'resources/list', 'resources/templates/list', 'resources/read', 'missing', 'server/discover'] as $method) {
            foreach ([[], ['name' => 'mcp_status'], ['name' => 'mcp_guide', 'arguments' => ['bad field /private' => true]], ['uri' => 'nc://files/private']] as $params) {
                $requests[] = json_encode(['jsonrpc' => '2.0', 'id' => 'synthetic', 'method' => $method, 'params' => $params]);
            }
        }
        foreach (['', \OCA\Mcp\Mcp\Protocol\ProtocolMetadata::VERSION, \OCA\Mcp\Mcp\Protocol\ProtocolMetadata::MODERN_VERSION, 'garbage'] as $header) {
            foreach ($requests as $raw) {
                $protocolCases[] = $protocol->handle($raw, $header, 'all');
            }
        }
        $results = [];
        foreach (['en', 'pt_BR', 'es'] as $locale) {
            Translator::use(new JsonL10n($locale));
            [$registry, $policy] = $this->boot();
            $this->grants($policy, 'alice', true);
            $results[$locale]['read'] = $registry->call('files_read', [], 'alice');
            $results[$locale]['preview'] = $registry->call('files_edit', [], 'alice');
            $results[$locale]['write'] = $registry->call('files_edit', ['confirm' => true], 'alice');
            $this->failure = new PlanChanged(['action' => 'update', 'message' => 'Synthetic changed state']);
            $results[$locale]['changed'] = $registry->call('files_edit', ['confirm' => true], 'alice');
            $this->failure = new ToolFailure('Synthetic refusal');
            $results[$locale]['refusal'] = $registry->call('files_read', [], 'alice');
            $this->failure = new \RuntimeException('Synthetic private state');
            $results[$locale]['unexpected'] = $registry->call('files_read', [], 'alice');
            $this->failure = null;
        }
        return ['publication' => $publication, 'protocol' => $protocolCases, 'results' => $results];
    }

    public function testFrozenSharedContracts(): void {
        foreach ($this->capture() as $name => $data) {
            self::assertSame(file_get_contents(dirname(__DIR__, 2).'/Support/Mcp/Compatibility/'.$name.'.json'),
                json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR)."\n");
        }
    }

    public function testSharedPublicationRechecksIdentityGrantsAppsAndLocale(): void {
        [$registry, $policy, , $resources] = $this->boot();
        $this->grants($policy, 'alice', true);
        $this->grants($policy, 'bob', false);
        self::assertCount(4, $registry->definitions('alice'));
        self::assertSame([], $registry->definitions('bob'));
        $this->enabled = false;
        self::assertCount(3, $registry->definitions('alice'));
        $this->refused(fn () => $registry->call('notes_list', [], 'alice'));
        $this->enabled = true; $this->version = '0.0.1';
        self::assertCount(3, $registry->definitions('alice'));
        $this->version = '';
        $this->role = false;
        self::assertSame([], $registry->definitions('alice'));
        $this->role = true;
        $policy->setGrant('alice', 'files', 'read', false);
        self::assertCount(2, $registry->definitions('alice'));
        self::assertSame([], array_filter($this->events, static fn ($e) => is_array($e) && $e[0] === 'call'));
        $policy->setGrant('alice', 'files', 'read', true);
        $english = $registry->list('alice');
        Translator::use(new JsonL10n('es'));
        self::assertNotSame($english, $registry->list('alice'));
        self::assertSame($registry->call('mcp_guide', [], 'alice')['content'][0]['text'], $resources->read('mcp://guide', 'alice')['contents'][0]['text']);
    }

    public function testSharedExecutionPreservesAuditAndFailureOrder(): void {
        [$registry, $policy] = $this->boot();
        $registry->call('files_read', [], 'alice');
        self::assertSame([['call', ['n' => 5], 'alice'], ['success', ['n' => 5]]], $this->events);
        $this->events = []; $this->role = false;
        $this->refused(fn () => $registry->call('files_read', [], 'alice'));
        self::assertSame([['denied', []]], $this->events);
        $this->events = []; $this->role = true;
        $this->refused(fn () => $registry->call('files_read', ['n' => '5'], 'alice'));
        self::assertSame([['invalid', ['n' => '5']]], $this->events);
        $this->events = []; $this->auditFails = $this->loggerFails = true;
        self::assertTrue($registry->call('files_read', [], 'alice')['isError']);
        self::assertSame([['call', ['n' => 5], 'alice'], ['success', ['n' => 5]], 'logger'], $this->events);
        $this->events = []; $this->failure = new \RuntimeException('private');
        try { $registry->call('files_read', [], 'alice'); self::fail('Expected logger failure'); }
        catch (\RuntimeException $e) { self::assertSame('synthetic logger failure', $e->getMessage()); }
        self::assertSame([['call', ['n' => 5], 'alice'], 'logger'], $this->events);
        $this->events = []; $this->roleFails = true;
        try { $registry->call('files_read', [], 'alice'); self::fail('Expected role failure'); }
        catch (\RuntimeException $e) { self::assertSame('synthetic role failure', $e->getMessage()); }
        self::assertSame([], $this->events);
    }

    public function testSharedConfirmationRemainsStatelessAndBound(): void {
        [$registry, $policy] = $this->boot();
        $policy->setGrant('alice', 'files', 'edit', true);
        foreach ([[], ['confirm' => false]] as $args) {
            self::assertTrue($registry->call('files_edit', $args, 'alice')['structuredContent']['requiresConfirmation']);
        }
        self::assertSame([], $this->events);
        $this->refused(fn () => $registry->call('files_edit', ['confirm' => 'true'], 'alice'));
        $this->events = []; $this->failure = new PlanChanged(['action' => 'update']);
        self::assertTrue($registry->call('files_edit', ['confirm' => true], 'alice')['structuredContent']['requiresConfirmation']);
        self::assertCount(1, $this->events); // Call, without success audit.
        $state = new PlanState((new InMemoryConfig())->mock($this));
        $token = $state->of('files_edit', 'alice', ['etag' => 'one']);
        self::assertTrue(PlanState::matches($token, ['plan_state' => $token]));
        foreach ([['files_edit', 'bob', ['etag' => 'one']], ['files_share', 'alice', ['etag' => 'one']], ['files_edit', 'alice', ['etag' => 'two']]] as $input) {
            self::assertFalse(PlanState::matches($state->of(...$input), ['plan_state' => $token]));
        }
    }

    public function testSharedProtocolPreservesBothEraBoundaries(): void {
        [, , $protocol] = $this->boot();
        self::assertSame(['status' => 202, 'body' => null], $protocol->handle('{"jsonrpc":"2.0","method":"notifications/initialized"}', 'garbage', 'alice'));
        $ping = $protocol->handle('{"jsonrpc":"2.0","id":1,"method":"ping"}', '', 'alice');
        self::assertInstanceOf(\stdClass::class, $ping['body']['result']);
        $raw = '{"jsonrpc":"2.0","id":1,"method":"'."\xFF".'"}';
        self::assertSame(-32700, $protocol->handle($raw, '', 'alice')['body']['error']['code']);
        $result = ToolResult::structured('Synthetic', ['raw' => "\xFF"]);
        self::assertSame("\xFF", $result['structuredContent']['raw']);
    }
}
