	protected function setUp(): void {
		$this->tree = new FakeTree($this);
		$this->noteId = $this->tree->addFile('/alice/files/Notes/Reuniões/Ata.md', "Linha 1\nLinha 2", 'text/markdown');
		$this->tree->addFolder('/alice/files/Notes/Projetos');
		$this->config = new InMemoryConfig();

		$root = $this->createMock(IRootFolder::class);
		$root->method('getUserFolder')->willReturnCallback(fn () => $this->tree->rootFolder());
		$apps = $this->createMock(IAppManager::class);
		$apps->method('isEnabledForUser')->willReturn(true);
		$users = $this->createMock(IUserManager::class);
		$users->method('get')->willReturn($this->createMock(IUser::class));
		$access = new NodeAccessInfo(FakeUsers::manager($this, FakeUsers::DEFAULTS), $this->tree->shareManager());
		$this->module = new NotesModule(
			new NotesRepository($root, $this->config->mock($this)),
			$apps,
			$users,
			new SharedWriteGuard($access),
			$access,
			null,
			null,
			new \OCA\Mcp\Mcp\Confirmation\PlanState($this->config->mock($this)),
		);
		$this->renderer = new NotesPlanRenderer();
	}

	protected function tearDown(): void {
		Translator::reset();
	}

	public function testCreateNoteInEnglishAndPortuguese(): void {
		$plan = $this->module->preview('notes_create', [
			'title' => 'Roteiro',
			'content' => 'Passo 1: planejar',
			'category' => 'Projetos',
		], 'alice');

		// English
		$en = $this->renderer->render('notes_create', $plan);
		$this->assertNotNull($en);
		$this->assertStringContainsString('Create note in *Projetos*: **Roteiro**', $en);
		$this->assertStringContainsString('- Content: Passo 1: planejar', $en);

		// pt_BR
		Translator::use(new JsonL10n('pt_BR'));
		$pt = $this->renderer->render('notes_create', $plan);
		$this->assertNotNull($pt);
		$this->assertStringContainsString('Criar nota em *Projetos*: **Roteiro**', $pt);
		$this->assertStringContainsString('- Conteúdo: Passo 1: planejar', $pt);
	}

